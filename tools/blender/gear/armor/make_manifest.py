"""make_manifest.py -- collect the per-piece fragments (_work/pieces/*.json, _work/base_*.json) into
game/assets/gear/gear_manifest_armor.json (read by RENDER) and write game/assets/gear/armor/REGIONS.md.

Plain python (no bpy):  "C:\\Program Files\\Blender Foundation\\Blender 5.2\\5.2\\python\\bin\\python.exe" -I make_manifest.py
"""
import json, os, glob, time

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(HERE, "_work")
GEAR = r"Y:\game\assets\gear"
CLASSES = ["emberblade", "astromancer", "hunter", "soulbinder", "wildsoul", "forgebody", "lampknight", "pactbinder"]
SLOTS = ["helm", "chest", "gloves", "pants", "boots"]
LOOKS = ["t1", "t2", "t3", "t4"]
SKIN_REGIONS = ["head", "neck", "torso", "upper_arms", "forearms", "hands", "hips", "thighs", "shins", "feet"]
OTHER = ["hair", "beard", "brows", "wrap_loin", "wrap_chest"]
REGION_MESH = {r: "body_" + r for r in SKIN_REGIONS}
REGION_MESH.update({r: r for r in OTHER})
SLOT_OWNS = {"helm": ["hair", "beard", "brows", "head"], "chest": ["torso", "upper_arms", "neck", "wrap_chest"],
             "gloves": ["hands", "forearms"], "pants": ["hips", "thighs", "shins", "wrap_loin"], "boots": ["feet", "shins"]}

entries = []
for p in sorted(glob.glob(os.path.join(WORK, "pieces", "arm_*.json"))):
    with open(p, encoding="utf8") as f:
        e = json.load(f)
    if not os.path.isfile(os.path.join(GEAR, "armor", e["id"] + ".glb")):
        continue
    keep = ("id", "kind", "class", "class_key", "slot", "look", "file", "hides", "meshes", "triangles", "materials", "shared_textures", "bbox")
    entries.append({k: e[k] for k in keep if k in e})
order = {(c, s, l): i for i, (c, s, l) in enumerate((c, s, l) for c in CLASSES for s in SLOTS for l in LOOKS)}
entries.sort(key=lambda e: order.get((e["class_key"], e["slot"], e["look"]), 9999))
bodies = []
for c in CLASSES:
    p = os.path.join(WORK, "base_%s.json" % c)
    if not os.path.isfile(p) or not os.path.isfile(os.path.join(r"Y:\game\assets\chars", "hero_%s_base.glb" % c)):
        continue
    with open(p, encoding="utf8") as f:
        b = json.load(f)
    bodies.append(dict(id=b["id"], kind="body", class_key=c, file=b["file"], sex=b["kind"], triangles=b["triangles"],
                       regions={m["region"]: n for n, m in sorted(b["meshes"].items())}, textures=b["textures"]))
doc = dict(version=1, generated=time.strftime("%Y-%m-%d %H:%M"), author="ART-A",
           note="hides = body region tokens (see armor/REGIONS.md); token T hides the base-body mesh body_T, or T for hair / beard / brows / wrap_loin / wrap_chest",
           regions=REGION_MESH, slot_owns=SLOT_OWNS, bodies=bodies, entries=entries)
os.makedirs(GEAR, exist_ok=True)
with open(os.path.join(GEAR, "gear_manifest_armor.json"), "w", encoding="utf8") as f:
    json.dump(doc, f, indent=1)

have = {(e["class_key"], e["slot"], e["look"]) for e in entries}
lines = []
for c in CLASSES:
    row = []
    for l in LOOKS:
        n = sum((c, s, l) in have for s in SLOTS)
        row.append("%s %d/5" % (l, n))
    lines.append("| %s | %s | %s |" % (c, "yes" if any(b["class_key"] == c for b in bodies) else "-", " | ".join(row)))


def hides_table():
    out = []
    for e in entries:
        out.append("| `%s` | %s | %d |" % (e["id"], ", ".join(e["hides"]) or "-", e["triangles"]))
    return "\n".join(out)


md = """# Body regions and what each armour piece hides (ART-A)

Generated by `tools/blender/gear/armor/make_manifest.py` -- do not edit by hand. Machine-readable twin:
`game/assets/gear/gear_manifest_armor.json` (`entries[].hides`, `bodies[].regions`, `regions`, `slot_owns`).

## 1. The base body `game/assets/chars/hero_<class>_base.glb`

Same skeleton (65 UAL bones, same names, same rest pose) as `hero_<class>.glb`; no weapon, no animation.
One skinned mesh node per region; a piece's `hides` lists region TOKENS:

| token | mesh node | what it is | border (rest pose, metres; Blender Z up = Godot Y up) |
|---|---|---|---|
| `head` | `body_head` | face, ears, scalp skin, eyeballs | above the jaw line (skin weighted to the Head bone) |
| `neck` | `body_neck` | neck | between head and the collar line (height about 1.50) |
| `torso` | `body_torso` | chest, belly, back, shoulders up to the armhole | height 1.005 (waist) .. collar; |x| < 0.205 at the shoulders |
| `upper_arms` | `body_upper_arms` | shoulder cap to elbow | |x| 0.205 .. 0.466 |
| `forearms` | `body_forearms` | elbow to wrist | |x| 0.466 .. wrist |
| `hands` | `body_hands` | hands | skin weighted to hand / finger bones |
| `hips` | `body_hips` | pelvis, buttocks, groin | height 0.80 .. 1.005 |
| `thighs` | `body_thighs` | thigh and knee | height 0.44 .. 0.80 |
| `shins` | `body_shins` | below the kneecap to above the ankle | height 0.125 .. 0.44 |
| `feet` | `body_feet` | feet with ankles (bare) | below 0.125 |
| `hair` | `hair` | scalp hair (plus a bound topknot where the class has one). Absent on a bald class | |
| `beard` | `beard` | facial hair (only where the class has one) | |
| `brows` | `brows` | eyebrows | |
| `wrap_loin` | `wrap_loin` | the linen loincloth (band, cloth between the legs, flaps, cord) | |
| `wrap_chest` | `wrap_chest` | the linen chest wrap (female bodies only) | |

Matching rule that works for every token: strip a leading `body_` from both the token and the node name and compare
(`GearVisual.HideRegion` already does this with a prefix test; no token is a prefix of another node's name).

Materials: `skin_hero_<class>_base` (all `body_*` meshes: ONE 2048 atlas), `hair_hero_<class>_base` (hair, beard, brows),
`cloth_hero_<class>_base` (wraps; the forgebody topknot is a second surface of `hair`). The regions were cut out of one
baked mesh: normals, UVs and tangents are identical on both sides of every border, so there is no shading seam between
neighbouring regions (do not let an importer regenerate normals or tangents; LOD generation per region mesh can open
hairline cracks at the borders at coarse LODs -- heroes should stay on LOD 0).

## 2. Armour pieces `game/assets/gear/armor/arm_<class>_<slot>_<t1..t4>.glb`

* Skinned to the same 65-bone skeleton (the file contains the full armature, rest pose identical to the hero's).
* Mesh nodes: `arm_<class>_<slot>_<look>` (one mesh; t4 has one surface per material of today's hero, t1-t3 a single
  surface with one atlas), optionally `..._emis` (emissive, material name starts with `emis`) and `..._skin`.
* **Carried skin (`..._skin`)**: when a piece takes over a region but leaves part of it visible (an open collar, short
  sleeves, a bare midriff, torn cloth), the visible remainder of that region's skin -- cut from the base body, same
  vertices, normals, UVs, material and texture files -- travels inside the piece. So `hides` is always safe to apply
  as a whole-mesh switch: nothing visible is lost and no skin is left under the armour to poke through.
* `hides` is also stored in the file: scene extras and node extras `hide_body_regions` ("torso,upper_arms").
* Regions a piece does NOT hide stay visible under / next to it; what lies over them is either an offset shell with
  the skin's own weights or stands clear of the skin.

### Which slot may hide what (ownership)

| slot | may hide | notes |
|---|---|---|
| helm | `hair`, `beard`, `brows`, `head` | `hair` whenever the piece covers the scalp (hoods, caps, helms); `head` only for fully closed helms |
| chest | `torso`, `upper_arms`, `neck`, `wrap_chest` | sleeves that reach past the elbow lie over `forearms` without hiding them |
| gloves | `hands`, `forearms` | |
| pants | `hips`, `thighs`, `shins`, `wrap_loin` | every pants piece hides `wrap_loin` + `hips` (exception: thigh-high hose such as the lampknight t4, see table) |
| boots | `feet`, `shins` | `shins` is shared: both pieces may hide it, both may carry its remainder (identical skin, no artefact) |

### Layering, so that looks can be mixed

Offsets from the skin in the zones where two slots overlap:

| zone | under | over |
|---|---|---|
| waist (height 0.98-1.06) | pants: fitted, at most 11 mm, top edge at or below 1.03 | chest hem: 15 mm or more; belts, sashes and everything hung from them belong to the chest piece |
| wrist | tight sleeves (chest): at most 7 mm | glove cuffs / bracers: 9-18 mm; wide sleeves (chest): 25 mm or more, outside everything |
| shin | pants legs: at most 11 mm | boot shafts: 13-18 mm (boots are worn over the pants) |
| neck | chest collar / gorget | helm, coif and hood skirts are the outermost layer |

t4 pieces are today's hero cut apart, so their offsets are whatever the hero had; see the per-class notes in
`tools/gear/PROGRESS_ARTA.md` for the combinations that were checked.

### Textures (VRAM)

* t4 pieces carry NO textures of their own: they reference today's hero atlases
  `res://assets/chars/hero_<class>_{cloth,leather,metal,bone}_{c,n,orm}.jpg` and `..._emis_g.png` by relative URI
  (`../../chars/...`). A full t4 set therefore costs exactly what the baked hero costs, and the baked hero and the
  pieces share the same GPU textures.
* Carried skin references the base body's skin atlas `hero_<class>_base_skin_{c,n,orm}.jpg` the same way.
* t1-t3 pieces embed ONE atlas each (`gear_c / gear_n / gear_orm`, extracted by the importer next to the file):
  wearing a mixed set loads the textures of the worn pieces only.
* Import order: the hero / base `.glb` files must have been imported once (their textures extracted) before the
  armour files; `tools/import.ps1` run twice after a clean checkout does it.

## 3. Status

| class | base body | t1 | t2 | t3 | t4 |
|---|---|---|---|---|---|
%s

## 4. Hides per piece

| piece | hides | triangles |
|---|---|---|
%s
""" % ("\n".join(lines), hides_table())
with open(os.path.join(GEAR, "armor", "REGIONS.md"), "w", encoding="utf8") as f:
    f.write(md)
print("manifest: %d armour entries, %d bodies" % (len(entries), len(bodies)))
