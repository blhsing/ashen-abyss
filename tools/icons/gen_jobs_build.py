def sheet(sid, accent, *cells):
    assert len(cells) == 9, sid
    J.append(dict(id=sid, grid=3, extra="Accent colour of the magical effects in this sheet: %s. " % accent,
                  cells=[c[0] for c in cells], subjects=[c[1] for c in cells]))


